#!/bin/sh
# Writes internal/legal/third_party_licenses.txt: the full licence text of
# every third-party Go module compiled into the binaries (both cmd/), as
# their licences require when the binaries are distributed (Docker image).
# CI fails if the committed file is out of date (make licenses-check).
set -eu
cd "$(dirname "$0")/.."
out=internal/legal/third_party_licenses.txt
main=$(go list -m)
{
  echo "Third-party software included in QR dinàmics"
  echo "Generated by scripts/third-party-licenses.sh from go.mod; do not edit."
  echo
  echo "================================================================"
  echo "Go standard library and runtime $(go env GOVERSION)"
  echo "================================================================"
  goroot=$(go env GOROOT)
  # Homebrew keeps the Go LICENSE one level above GOROOT.
  if [ -f "$goroot/LICENSE" ]; then cat "$goroot/LICENSE"; else cat "$goroot/../LICENSE"; fi
  go list -deps -f '{{with .Module}}{{.Path}} {{.Version}} {{.Dir}}{{end}}' ./cmd/... |
    sort -u | grep -v "^$main " |
    while read -r path version dir; do
      lic=$(ls "$dir" | grep -iE '^(licen[cs]e|copying)(\.md|\.txt)?$' | head -1 || true)
      [ -n "$lic" ] || { echo "no licence file for $path" >&2; exit 1; }
      echo
      echo "================================================================"
      echo "$path $version"
      echo "================================================================"
      cat "$dir/$lic"
      [ -f "$dir/NOTICE" ] && { echo; echo "--- NOTICE ---"; cat "$dir/NOTICE"; }
      true
    done
} > "$out"
grep -c '^====' "$out" | awk '{print $1/2 " components"}'
